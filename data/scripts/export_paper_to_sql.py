#!/usr/bin/env python3
"""Export one parsed paper and its AI assessment as PostgreSQL seed SQL."""

from __future__ import annotations

import argparse
import csv
import json
import re
import unicodedata
from pathlib import Path


def sanitize_text(value: str) -> str:
    """Remove characters PostgreSQL TEXT cannot safely store from PDF extraction."""
    cleaned = []
    for char in value:
        codepoint = ord(char)
        category = unicodedata.category(char)
        if char in "\n\r\t":
            cleaned.append(char)
        elif codepoint == 0 or category in {"Cc", "Cs"}:
            cleaned.append(" ")
        else:
            cleaned.append(char)
    return re.sub(r"[ \t]+\n", "\n", "".join(cleaned))


def lit(value):
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "TRUE" if value else "FALSE"
    if isinstance(value, (int, float)):
        return str(value)
    return "'" + sanitize_text(str(value)).replace("'", "''") + "'"


def json_lit(value):
    return lit(json.dumps(value, ensure_ascii=False)) + "::jsonb"


def insert(table, columns, values, conflict="DO NOTHING"):
    return (
        f"INSERT INTO {table} ({', '.join(columns)})\n"
        f"VALUES ({', '.join(values)})\nON CONFLICT {conflict};\n"
    )


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--project-root", type=Path, required=True)
    parser.add_argument("--paper-id", required=True)
    parser.add_argument("--version", required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()

    root = args.project_root
    version_id = f"{args.paper_id}_{args.version}"
    parsed = root / "data" / "parsed" / args.paper_id / args.version
    source = json.loads((root / "data" / "source_snapshots" / args.paper_id / "source_record.json").read_text())
    metadata = json.loads((parsed / "metadata.json").read_text())
    sections = json.loads((parsed / "sections.json").read_text())
    elements = json.loads((parsed / "elements.json").read_text())
    links_path = parsed / "links.json"
    links = json.loads(links_path.read_text()) if links_path.exists() else []
    descriptors_path = parsed / "semantic_descriptors.json"
    descriptors = json.loads(descriptors_path.read_text()) if descriptors_path.exists() else []
    chunks = [json.loads(line) for line in (parsed / "chunks.jsonl").read_text().splitlines() if line]
    assessment = json.loads((root / "data" / "annotations" / "ai_trial" / f"{args.paper_id}.json").read_text())
    release = json.loads((root / "data" / "manifests" / "release.json").read_text())
    manifest_row = next(r for r in csv.DictReader((root / "data/manifests/papers.csv").open())
                        if r["paper_id"] == args.paper_id)

    lines = [
        "-- Generated by scripts/export_paper_to_sql.py; do not edit manually.",
        "-- Requires sql/001_initial_schema.sql.",
        "BEGIN;\n",
    ]
    lines.append(insert("papers", [
        "paper_id", "title", "authors", "authors_status", "language", "arxiv_id", "openreview_forum_id",
        "venue", "publication_year", "abstract", "doi"
    ], [
        lit(source["paper_id"]), lit(source["title"]), json_lit(source["authors"]),
        lit(source.get("authors_status") or ("verified" if source.get("authors") else "missing_requires_review")),
        lit(source.get("language", "en")), lit(source.get("arxiv_id")),
        lit(source.get("openreview_forum_id")), lit(source.get("venue")),
        lit(source.get("publication_year")), lit(source.get("abstract")), lit(source.get("doi"))
    ]))
    lines.append(insert("paper_versions", [
        "paper_version_id", "paper_id", "version_label", "source_type", "source_url",
        "pdf_object_key", "pdf_sha256", "retrieved_at", "page_count", "parser_name",
        "parser_version", "parse_status", "parse_quality", "parse_warnings", "has_ocr",
        "reading_order_quality"
    ], [
        lit(version_id), lit(args.paper_id), lit(args.version), lit(metadata["source_type"]),
        lit(metadata["source_url"]), lit(metadata["pdf_object_key"]), lit(metadata["pdf_sha256"]),
        lit(source["retrieved_at"]), lit(metadata["page_count"]), lit(metadata["parser_name"]),
        lit(metadata["parser_version"]), lit(metadata["parse_status"]), lit(metadata["parse_quality"]),
        json_lit(metadata["parse_warnings"]), lit(metadata["has_ocr"]), lit(metadata["reading_order_quality"])
    ]))

    for row in sections:
        lines.append(insert("paper_sections", [
            "section_id", "paper_version_id", "parent_section_id", "section_number", "title",
            "section_role", "level", "sequence_index", "page_start", "page_end"
        ], [lit(row.get(c)) for c in [
            "section_id", "paper_version_id", "parent_section_id", "section_number", "title",
            "section_role", "level", "sequence_index", "page_start", "page_end"
        ]]))

    for row in chunks:
        lines.append(insert("paper_text_chunks", [
            "chunk_id", "paper_version_id", "section_id", "sequence_index", "chunk_index_in_section",
            "page_start", "page_end", "content_type", "text_content", "token_count", "char_count",
            "location_confidence"
        ], [lit(row.get(c)) for c in [
            "chunk_id", "paper_version_id", "section_id", "sequence_index", "chunk_index_in_section",
            "page_start", "page_end", "content_type", "text_content", "token_count", "char_count",
            "location_confidence"
        ]]))

    for row in elements:
        lines.append(insert("paper_elements", [
            "element_id", "paper_version_id", "section_id", "element_type", "label", "caption",
            "page_number", "extracted_text", "asset_object_key", "parse_quality"
        ], [lit(row.get(c)) for c in [
            "element_id", "paper_version_id", "section_id", "element_type", "label", "caption",
            "page_number", "extracted_text", "asset_object_key", "parse_quality"
        ]]))

    for row in links:
        lines.append(insert("paper_links", [
            "paper_link_id", "paper_version_id", "source_chunk_id", "link_type",
            "url", "access_status", "checked_at"
        ], [lit(row.get(c)) for c in [
            "paper_link_id", "paper_version_id", "source_chunk_id", "link_type",
            "url", "access_status", "checked_at"
        ]]))

    for row in descriptors:
        lines.append(insert("paper_semantic_descriptors", [
            "descriptor_id", "paper_version_id", "descriptor_group", "descriptor_type",
            "descriptor_text", "evidence_chunk_id", "evidence_element_id", "confidence"
        ], [lit(row.get(c)) for c in [
            "descriptor_id", "paper_version_id", "descriptor_group", "descriptor_type",
            "text", "evidence_chunk_id", "evidence_element_id", "confidence"
        ]]))

    lines.append(insert("rubric_versions", [
        "rubric_id", "rubric_version", "name", "definition", "status"
    ], [
        lit(assessment["rubric_id"]), lit(assessment["rubric_version"]),
        lit("ICLR-inspired paper due-diligence rubric"),
        json_lit({"dimensions": [x["dimension_id"] for x in assessment["dimension_assessments"]]}),
        lit("draft")
    ]))
    model_run_id = assessment.get("model_run", {}).get("model_run_id") or f"model_run_ai_trial_{args.paper_id}_{args.version}"
    model = assessment.get("model_run", {})
    lines.append(insert("model_runs", [
        "model_run_id", "paper_version_id", "provider", "model_id", "model_version", "prompt_version",
        "rubric_id", "rubric_version", "status", "raw_output_object_key", "raw_output_sha256", "validation_errors"
    ], [
        lit(model_run_id), lit(version_id), lit(model.get("provider", "unknown")), lit(model.get("model_id", "unknown")),
        lit(model.get("model_version", "unknown")), lit(model.get("prompt_version", "unknown")),
        lit(assessment["rubric_id"]), lit(assessment["rubric_version"]),
        lit("completed" if assessment.get("stage")=="report_ready" else "queued"),
        lit(f"data/model_runs/{model_run_id}.json" if model.get("raw_output_sha256") else None),
        lit(model.get("raw_output_sha256")), json_lit([])
    ]))
    lines.append(insert("assessments", [
        "assessment_id", "paper_version_id", "assessment_type", "model_run_id", "schema_version",
        "rubric_id", "rubric_version", "status", "paper_summary", "overall_score", "overall_rating",
        "reading_recommendation", "confidence", "is_provisional", "stage", "provisional_reason",
        "overall_assessment", "strengths", "concerns", "unresolved_questions",
        "limitations_of_assessment", "guardrails"
    ], [
        lit(assessment["assessment_id"]), lit(version_id), lit("ai"), lit(model_run_id),
        lit(assessment["schema_version"]), lit(assessment["rubric_id"]), lit(assessment["rubric_version"]),
        lit(assessment["status"]), lit(assessment["paper_summary"]), lit(assessment["overall_score"]),
        lit(assessment["overall_rating"]), lit(assessment["reading_recommendation"]),
        lit(assessment["confidence"]), lit(assessment["is_provisional"]), lit(assessment.get("stage")),
        lit(assessment.get("provisional_reason")), lit(assessment.get("overall_assessment")),
        json_lit(assessment.get("strengths", [])), json_lit(assessment.get("concerns", [])),
        json_lit(assessment.get("unresolved_questions", [])),
        json_lit(assessment.get("limitations_of_this_assessment", [])),
        json_lit(assessment.get("guardrails", {}))
    ]))

    dimension_ids = {}
    for row in assessment["dimension_assessments"]:
        dimension_assessment_id = f"dim_{args.paper_id}_{row['dimension_id']}"
        dimension_ids[row["dimension_id"]] = dimension_assessment_id
        lines.append(insert("dimension_assessments", [
            "dimension_assessment_id", "assessment_id", "dimension_id", "applicability", "score",
            "rating", "weight", "dimension_question", "summary", "strengths", "weaknesses",
            "rationale", "confidence", "uncertainty_reason"
        ], [
            lit(dimension_assessment_id), lit(assessment["assessment_id"]), lit(row["dimension_id"]),
            lit(row["applicability"]), lit(row["score"]), lit(row["rating"]), lit(row["weight"]),
            lit(row.get("dimension_question", row["dimension_id"])), lit(row["summary"]),
            json_lit(row.get("strengths", [])), json_lit(row.get("weaknesses", [])),
            lit(row.get("rationale", row["summary"])), lit(row["confidence"]),
            lit(row.get("uncertainty_reason"))
        ]))

    element_by_label = {row["label"]: row["element_id"] for row in elements}
    for ev in assessment["evidence_references"]:
        label = ev["locator_label"]
        chunk_id = label if label.startswith(version_id + "_chunk_") else None
        element_id = element_by_label.get(label)
        lines.append(insert("evidence_references", [
            "evidence_id", "assessment_id", "chunk_id", "element_id", "page_number", "section_title",
            "locator_type", "locator_label", "evidence_mode", "excerpt", "location_confidence",
            "section_id", "location_caveat", "is_absence_evidence"
        ], [
            lit(ev["evidence_id"]), lit(assessment["assessment_id"]), lit(chunk_id), lit(element_id),
            lit(ev["page_number"]), lit(ev["section_title"]), lit(ev["locator_type"]), lit(label),
            lit(ev["evidence_mode"]), lit(ev["excerpt"]), lit(ev["location_confidence"]),
            lit(ev.get("section_id")), lit(ev.get("location_caveat")),
            lit(ev.get("is_absence_evidence", False))
        ]))

    for index, link in enumerate(assessment.get("evidence_links", []), 1):
        lines.append(insert("assessment_evidence_links", [
            "evidence_link_id", "dimension_assessment_id", "evidence_id", "stance", "reason"
        ], [
            lit(f"link_{args.paper_id}_{index:03d}"), lit(dimension_ids[link["dimension_id"]]),
            lit(link["evidence_id"]), lit(link["stance"]), lit(link["reason"])
        ]))

    for row in assessment.get("claimed_contributions", []):
        lines.append(insert("claimed_contributions", [
            "contribution_id", "assessment_id", "contribution_text", "contribution_type", "evidence_id"
        ], [
            lit(f"{args.paper_id}_{row['contribution_id']}"), lit(assessment["assessment_id"]),
            lit(row["text"]), lit(row["type"]), lit(row.get("evidence_id"))
        ]))

    for row in assessment.get("claim_checks", []):
        lines.append(insert("claim_checks", [
            "claim_id", "assessment_id", "claim_text", "claim_type", "scope", "verdict",
            "reasoning", "evidence_ids"
        ], [
            lit(f"{args.paper_id}_{row['claim_id']}"), lit(assessment["assessment_id"]),
            lit(row["claim_text"]), lit(row["claim_type"]), lit(row.get("scope")),
            lit(row["verdict"]), lit(row["reasoning"]), json_lit(row.get("evidence_ids", []))
        ]))

    for row in assessment["reproducibility_checks"]:
        lines.append(insert("reproducibility_checks", [
            "reproducibility_check_id", "assessment_id", "check_id", "status", "detail", "evidence_ids"
        ], [
            lit(f"repro_{args.paper_id}_{row['check_id']}"), lit(assessment["assessment_id"]),
            lit(row["check_id"]), lit(row["status"]), lit(row["detail"]),
            json_lit(row.get("evidence_ids", []))
        ]))

    lines.append(insert("dataset_releases", [
        "dataset_id", "dataset_version", "schema_version", "rubric_id", "rubric_version",
        "status", "gold_status"
    ], [lit(release[k]) for k in ("dataset_id", "dataset_version", "schema_version", "rubric_id",
                                  "rubric_version", "status", "gold_status")]))
    lines.append(insert("benchmark_memberships", [
        "dataset_id", "dataset_version", "paper_version_id", "split", "sample_quality_band",
        "decision", "decision_verified", "ai_assessment_id", "gold_assessment_id", "annotation_status"
    ], [
        lit(release["dataset_id"]), lit(release["dataset_version"]), lit(version_id),
        lit(manifest_row.get("dataset_split") or "calibration"),
        lit(manifest_row.get("sample_quality_band") or None), lit(manifest_row.get("decision") or None),
        lit(manifest_row.get("decision_verified") == "true"),
        lit(assessment["assessment_id"] if assessment.get("stage")=="report_ready" else None),
        lit(None), lit("approved" if assessment.get("status")=="approved" else
                       "ai_provisional" if assessment.get("stage")=="report_ready" else "parsed")
    ]))

    lines.append("COMMIT;\n")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
