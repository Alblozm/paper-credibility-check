#!/usr/bin/env python3
"""Generate the papers-table seed SQL from the manifest + source records.

Emits INSERTs for the `papers` table ONLY. paper_versions is not written because
sql/001_initial_schema.sql declares pdf_object_key NOT NULL and pdf_sha256
CHAR(64) NOT NULL, and no PDF has been downloaded or hashed. Inventing a
placeholder hash would put an unverifiable value into the column the whole
provenance design rests on, so the version row waits for the file.

A paper is emitted only if it has a title, a non-empty author list and an
arxiv_id. Rows failing that are reported and skipped, never half-written.
"""
from __future__ import annotations
import csv, datetime, glob, json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CSV_PATH = os.path.join(ROOT, "data/manifests/papers.csv")
SNAPS = os.path.join(ROOT, "data/source_snapshots")
OUT = os.path.join(ROOT, "sql/010_seed_papers.sql")


def q(s):
    return "'" + str(s).replace("'", "''") + "'"


def main():
    out_path = sys.argv[1] if len(sys.argv) > 1 else OUT
    recs = {}
    for p in sorted(glob.glob(os.path.join(SNAPS, "*", "source_record.json"))):
        r = json.load(open(p, encoding="utf-8"))
        recs[r["paper_id"]] = r
    rows = {r["paper_id"]: r for r in csv.DictReader(open(CSV_PATH, encoding="utf-8"))}

    emit, skip, warn = [], [], []
    for pid in sorted(rows, key=lambda p: (len(p), p)):
        rec, row = recs.get(pid), rows[pid]
        if not rec:
            skip.append((pid, "no source_record.json"))
            continue
        if not rec.get("title") or not rec.get("authors") or not rec.get("arxiv_id"):
            skip.append((pid, "missing title / authors / arxiv_id"))
            continue
        if not (rec.get("abstract") or "").strip():
            warn.append((pid, "no abstract — column will be NULL"))
        emit.append((pid, rec, row))

    stamp = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d")
    L = [f"-- 010_seed_papers.sql — generated by scripts/export_papers_sql.py on {stamp}.",
         "-- Do not edit by hand; regenerate with `make sql`.",
         "-- Requires sql/001_initial_schema.sql. Run after 001 (and after 002 if you",
         "-- want paper_001's parsed sections/chunks/elements).",
         "--",
         "-- SCOPE: `papers` table only. See the module docstring in",
         "-- scripts/export_papers_sql.py for why paper_versions is excluded.",
         "--",
         f"-- {len(emit)} papers emitted, {len(skip)} skipped.", ""]
    for pid, why in skip:
        L.append(f"--   skipped {pid}: {why}")
    for pid, why in warn:
        L.append(f"--   warning {pid}: {why}")
    L += ["", "BEGIN;", ""]
    for pid, rec, row in emit:
        forum = row.get("openreview_forum_id") or None
        venue = rec.get("venue") or row.get("venue") or None
        year = rec.get("publication_year") or (row.get("year") or None)
        L.append("INSERT INTO papers (paper_id, title, authors, abstract, language, "
                 "arxiv_id, doi, openreview_forum_id, venue, publication_year, track)")
        L.append(f"VALUES ({q(pid)}, {q(rec['title'])}, "
                 f"{q(json.dumps(rec['authors'], ensure_ascii=False))}::jsonb, "
                 f"{q(rec['abstract']) if (rec.get('abstract') or '').strip() else 'NULL'}, 'en', {q(rec['arxiv_id'])}, "
                 f"{q(rec.get('doi') or '')}, {q(forum) if forum else 'NULL'}, "
                 f"{q(venue) if venue else 'NULL'}, {int(year) if year else 'NULL'}, "
                 "'Conference')")
        L.append("ON CONFLICT (paper_id) DO NOTHING;")
        # An earlier seed may already hold this paper with columns left NULL
        # (002_seed_paper_001.sql did exactly that). Fill only the gaps; never
        # overwrite a value that is already there.
        L.append(f"UPDATE papers SET abstract = COALESCE(abstract, "
                 f"{q(rec['abstract']) if (rec.get('abstract') or '').strip() else 'NULL'}),")
        L.append(f"                  doi      = COALESCE(doi, {q(rec.get('doi') or '')}),")
        L.append("                  updated_at = now()")
        L.append(f"WHERE paper_id = {q(pid)} AND (abstract IS NULL OR doi IS NULL);")
        L.append("")
    L += ["COMMIT;", "",
          "-- Post-import checks:",
          f"--   SELECT count(*) FROM papers;                          -- expect {len(emit)}",
          "--   SELECT paper_id FROM papers WHERE jsonb_array_length(authors)=0;   -- expect 0",
          "--   SELECT arxiv_id FROM papers GROUP BY 1 HAVING count(*)>1;          -- expect 0",
          "--   SELECT p.paper_id FROM papers p WHERE NOT EXISTS",
          "--     (SELECT 1 FROM paper_versions v WHERE v.paper_id=p.paper_id);",
          "--     ^ expected non-empty until the PDFs are downloaded and hashed."]
    open(out_path, "w", encoding="utf-8").write("\n".join(L) + "\n")
    print(f"[sql] {out_path}: {len(emit)} INSERTs, {len(skip)} skipped")
    for pid, why in skip:
        print(f"[sql]   skipped {pid}: {why}")
    for pid, why in warn:
        print(f"[sql]   WARN {pid}: {why}")


if __name__ == "__main__":
    main()
